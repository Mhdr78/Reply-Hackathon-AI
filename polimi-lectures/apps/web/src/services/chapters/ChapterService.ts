import { config } from '@/config';
import { toAppError } from '@/lib/errors';
import { http } from '@/lib/http';
import { chatbotCall } from '@/services/chatbotApi';
import { sleep } from '@/lib/format';
import { mockChapterDrafts } from '@/mocks/chapters';
import type { LectureChapters, Transcript } from '@/types/domain';
import { normalizeChapters } from './chapterizer';

/**
 * Chapter contract. Chapters are derived from the transcript, so they are requested *after* a transcript exists.
 *
 * In production the backend generates them with an LLM as the step right after transcription
 * (transcript → LLM → `ChapterDraft[]` → `normalizeChapters`) and stores the result; see docs/CHAPTERS.md.
 * The UI only depends on this interface, so swapping mock → LLM changes nothing in the components.
 */
export interface ChapterService {
  /** Resolves with the chapters for this transcript. Rejects with AppError('NOT_FOUND') if they don't exist yet. */
  getChapters(transcript: Transcript): Promise<LectureChapters>;
  /** Discard saved chapters and generate new ones (LLM-backed services only). */
  regenerate?(transcript: Transcript): Promise<LectureChapters>;
}

/** Mock: heuristic boundaries + placeholder titles, computed in the browser. Also works for locally loaded transcripts. */
export const mockChapterService: ChapterService = {
  async getChapters(transcript) {
    await sleep(config.mockLatencyMs * 1.5); // pretend an LLM call is happening
    return {
      lectureId: transcript.lectureId,
      source: 'mock',
      createdAt: new Date().toISOString(),
      chapters: normalizeChapters(mockChapterDrafts(transcript), transcript),
    };
  },
};

/** REST adapter. The backend returns already-normalized chapters (404 while they are still being generated). */
export const httpChapterService: ChapterService = {
  getChapters: (transcript) => http<LectureChapters>(`/lectures/${transcript.lectureId}/chapters`),
};

/* ---------------- Chatbot server: LLM-generated chapters (services/chatbot, lecturemind.chapters) ---------------- */

interface ServerChapters {
  lectureId: string;
  source: 'llm' | 'fake';
  durationS: number;
  chapters: { id: string; title: string; start: number; end: number; startSegmentId: string }[];
}

/** Snap the server's chapters onto the transcript shown in the app (same rules as every other chapter source). */
function fromServer(r: ServerChapters, transcript: Transcript): LectureChapters {
  return {
    lectureId: transcript.lectureId,
    source: r.source,
    chapters: normalizeChapters(r.chapters.map((c) => ({ start: c.start, title: c.title })), transcript, { minChapterSec: 5 }),
  };
}

const chaptersPath = (lectureId: string) => `/lectures/${encodeURIComponent(lectureId)}/chapters`;

/**
 * Saved chapters are returned directly. The first time, they are generated by the LLM on the server and saved in
 * the lecture's database, so each lecture costs one LLM call. Lectures the chatbot hasn't prepared, or an offline
 * server, fall back to the mock titles.
 */
export const chatbotChapterService: ChapterService = {
  async getChapters(transcript) {
    try {
      // POST = "get or generate": returns the saved chapters, and calls the LLM only if there are none yet.
      return fromServer(await chatbotCall<ServerChapters>(chaptersPath(transcript.lectureId), { method: 'POST', body: '{}' }), transcript);
    } catch (e) {
      const code = toAppError(e).code;
      // NOT_FOUND here means "No such endpoint": an older chatbot server without chapters (restart it).
      if (code === 'NOT_PREPARED' || code === 'SERVICE_UNAVAILABLE' || code === 'NOT_FOUND') {
        if (code === 'NOT_FOUND') console.warn('[chapters] The chatbot server has no chapters endpoint. Restart it (`npm run chatbot`) to get AI chapters.');
        return mockChapterService.getChapters(transcript);
      }
      throw e;
    }
  },
  async regenerate(transcript) {
    const r = await chatbotCall<ServerChapters>(chaptersPath(transcript.lectureId), { method: 'POST', body: JSON.stringify({ force: true }) });
    return fromServer(r, transcript);
  },
};
