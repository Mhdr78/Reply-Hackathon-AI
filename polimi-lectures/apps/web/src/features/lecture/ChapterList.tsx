import { memo, useEffect, useRef } from 'react';
import { useState } from 'react';
import { ListVideo, MessageSquareText, RotateCw, Sparkles } from 'lucide-react';
import { config } from '@/config';
import { cn, formatTimestamp } from '@/lib/format';
import { Skeleton } from '@/components/ui';
import { findChapterIndex } from '@/services/chapters/chapterizer';
import type { ChaptersState } from '@/hooks/useChapters';
import type { Chapter } from '@/types/domain';
import { usePlayback } from './playback';

const lengthLabel = (sec: number) => (sec < 60 ? `${Math.round(sec)} s` : `${Math.round(sec / 60)} min`);

/** The chapter list ("Chapters" tab). Clicking a chapter seeks the video to its start. */
export function ChapterList({ state, onRetry, onRegenerate, onSelect, onAsk }: { state: ChaptersState; onRetry: () => void; onRegenerate?: () => void; onSelect: (c: Chapter) => void; onAsk?: (c: Chapter) => void }) {
  if (state.status === 'loading' || state.status === 'idle') {
    return (
      <div className="mx-auto max-w-3xl space-y-2 p-3" aria-busy>
        <p className="flex items-center gap-2 px-1 pb-1 text-[12.5px] text-slate-500">
          <Sparkles className="size-3.5 shrink-0 animate-pulse text-brand-500" />
          {config.chatbotUrl ? 'Loading chapters… The first time, the AI reads the whole lecture, which can take up to a minute.' : 'Generating chapters from the transcript…'}
        </p>
        {Array.from({ length: 5 }, (_, i) => (
          <div key={i} className="flex gap-3 rounded-lg p-2.5">
            <Skeleton className="size-7 shrink-0 rounded-md" />
            <div className="flex-1 space-y-1.5"><Skeleton className="h-4 w-2/5" /><Skeleton className="h-3 w-4/5" /></div>
          </div>
        ))}
      </div>
    );
  }
  if (state.status === 'unavailable') {
    return (
      <Empty icon={<ListVideo className="size-5" />} title="No chapters yet" text="Chapters are generated automatically from the transcript. Check back in a few minutes." />
    );
  }
  if (state.status === 'error') {
    return (
      <Empty icon={<ListVideo className="size-5" />} title="Chapters could not be loaded" text={state.error.message}>
        <button onClick={onRetry} className="mt-4 inline-flex h-8 items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-3 text-[13px] font-medium text-slate-700 shadow-sm hover:bg-slate-50"><RotateCw className="size-3.5" />Try again</button>
      </Empty>
    );
  }
  return <ReadyList chapters={state.data.chapters} source={state.data.source} onSelect={onSelect} onAsk={onAsk} onRegenerate={onRegenerate} />;
}

function ReadyList({ chapters, source, onSelect, onAsk, onRegenerate }: { chapters: Chapter[]; source: string; onSelect: (c: Chapter) => void; onAsk?: (c: Chapter) => void; onRegenerate?: () => void }) {
  const active = usePlayback((s) => findChapterIndex(chapters, s.currentTime));
  const listRef = useRef<HTMLOListElement>(null);

  useEffect(() => {
    listRef.current?.querySelector<HTMLElement>(`[data-chapter="${active}"]`)?.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
  }, [active]);

  return (
    <div className="mx-auto max-w-3xl">
      <ol ref={listRef} className="space-y-0.5">
        {chapters.map((c, i) => (
          <ChapterItem key={c.id} chapter={c} index={i} active={i === active} past={i < active} onSelect={onSelect} onAsk={onAsk} />
        ))}
      </ol>
      <div className="mt-4 flex items-start gap-2 rounded-lg bg-slate-50 px-3 py-2.5 text-[12px] leading-relaxed text-slate-500">
        <Sparkles className="mt-0.5 size-3.5 shrink-0 text-slate-400" />
        <span className="min-w-0 flex-1">
          {source === 'llm' && 'Chapters generated by AI from the transcript and slides. Titles may be imperfect.'}
          {source === 'fake' && 'Fake chapters: the chatbot server is running with --fake-llm.'}
          {source === 'mock' && (config.chatbotUrl
            ? 'Placeholder chapters. AI chapters need the chatbot server running and this lecture’s transcript and slides (public/media/<id>.json and <id>/materials.json).'
            : 'Placeholder chapters. Connect the chatbot server to generate them with AI.')}
          {source === 'manual' && 'Chapters set by the instructor.'}
        </span>
        {onRegenerate && <RegenerateButton onConfirm={onRegenerate} />}
      </div>
    </div>
  );
}

function RegenerateButton({ onConfirm }: { onConfirm: () => void }) {
  const [confirm, setConfirm] = useState(false);
  return (
    <button
      onClick={() => (confirm ? onConfirm() : setConfirm(true))}
      onBlur={() => setConfirm(false)}
      title="Ask the AI to segment the lecture again (one LLM call)"
      className={cn('inline-flex shrink-0 items-center gap-1 rounded-md px-2 py-0.5 font-medium transition', confirm ? 'bg-amber-100 text-amber-800' : 'text-slate-600 hover:bg-slate-200/70')}
    >
      <RotateCw className="size-3" />{confirm ? 'Click again to regenerate' : 'Regenerate'}
    </button>
  );
}

const ChapterItem = memo(function ChapterItem({ chapter: c, index, active, past, onSelect, onAsk }: { chapter: Chapter; index: number; active: boolean; past: boolean; onSelect: (c: Chapter) => void; onAsk?: (c: Chapter) => void }) {
  return (
    <li data-chapter={index} className="group/item relative">
      <button
        onClick={() => onSelect(c)}
        aria-current={active || undefined}
        className={cn('group relative flex w-full gap-3 rounded-lg px-2.5 py-2.5 text-left transition-colors', active ? 'bg-brand-50' : 'hover:bg-slate-50')}
      >
        {active && <span className="absolute inset-y-2 left-0 w-[3px] rounded-full bg-brand-600" />}
        <span className={cn('mt-px grid size-7 shrink-0 place-items-center rounded-md text-[12px] font-semibold tabular', active ? 'bg-brand-600 text-white' : past ? 'bg-slate-100 text-slate-400' : 'bg-slate-100 text-slate-600 group-hover:bg-brand-100 group-hover:text-brand-700')}>
          {index + 1}
        </span>
        <span className="min-w-0 flex-1">
          <span className={cn('block text-[14.5px] font-medium leading-snug', active ? 'text-ink' : past ? 'text-slate-600' : 'text-slate-800')}>{c.title}</span>
          {c.summary && <span className="mt-0.5 line-clamp-2 block text-[13px] leading-relaxed text-slate-500">{c.summary}</span>}
          {active && <ChapterProgress chapter={c} />}
        </span>
        <span className="shrink-0 pt-0.5 text-right">
          <span className={cn('block font-mono text-[12px] tabular', active ? 'font-semibold text-brand-600' : 'text-slate-500 group-hover:text-brand-600')}>{formatTimestamp(c.start)}</span>
          <span className="block text-[11.5px] text-slate-400">{lengthLabel(c.end - c.start)}</span>
        </span>
      </button>
      {onAsk && (
        <button
          onClick={() => onAsk(c)}
          title="Ask AI about this chapter"
          aria-label={`Ask AI about chapter ${index + 1}`}
          className="absolute right-[72px] top-1/2 hidden -translate-y-1/2 items-center gap-1 rounded-md bg-white px-2 py-1 text-[11.5px] font-medium text-slate-600 shadow-sm ring-1 ring-slate-200 hover:text-brand-700 focus:inline-flex group-hover/item:inline-flex"
        >
          <MessageSquareText className="size-3.5" />Ask AI
        </button>
      )}
    </li>
  );
});

/** Thin progress bar inside the active chapter; only this component re-renders on every tick. */
function ChapterProgress({ chapter }: { chapter: Chapter }) {
  const pct = usePlayback((s) => Math.round(Math.max(0, Math.min(1, (s.currentTime - chapter.start) / (chapter.end - chapter.start))) * 200) / 2);
  return (
    <span className="mt-2 block h-1 overflow-hidden rounded-full bg-brand-100">
      <span className="block h-full rounded-full bg-brand-600 transition-[width] duration-300" style={{ width: `${pct}%` }} />
    </span>
  );
}

function Empty({ icon, title, text, children }: { icon: React.ReactNode; title: string; text: string; children?: React.ReactNode }) {
  return (
    <div className="grid h-full place-items-center p-8 text-center">
      <div className="max-w-sm">
        <div className="mx-auto grid size-10 place-items-center rounded-full bg-slate-100 text-slate-500">{icon}</div>
        <p className="mt-3 text-[14px] font-medium text-slate-800">{title}</p>
        <p className="mt-1 text-[13px] leading-relaxed text-slate-500">{text}</p>
        {children}
      </div>
    </div>
  );
}
